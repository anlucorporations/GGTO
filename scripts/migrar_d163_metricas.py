# Recálculo retroactivo de todas las jornadas con despachos (RGX de § 14).
RECALCULO = """
SELECT fn_recalcular_metricas_despacho_diarias(id_central, fecha)
FROM (SELECT DISTINCT id_central, fecha FROM despacho) jornadas
"""

VERIFICACION = """
SELECT
    (SELECT count(*) FROM information_schema.tables
      WHERE table_schema = 'public'
        AND table_name = 'despacho_metrica_diaria') AS tabla_ok,
    (SELECT count(*) FROM information_schema.routines
      WHERE routine_schema = 'public'
        AND routine_name = 'fn_recalcular_metricas_despacho_diarias') AS funcion_ok,
    (SELECT count(*) FROM information_schema.triggers
      WHERE trigger_name IN ('trg_despacho_caso_metricas',
                             'trg_caso_metricas_despacho')) AS triggers_ok,
    (SELECT count(*) FROM pg_policies
      WHERE schemaname = 'public' AND tablename = 'despacho_metrica_diaria'
        AND policyname = 'p_despacho_metrica_central') AS politica_ok,
    (SELECT count(DISTINCT (id_central, fecha)) FROM despacho) AS jornadas
"""

FILAS_METRICA = "SELECT count(*) FROM despacho_metrica_diaria"


def registrar(mensaje: str) -> None:
    LOG.parent.mkdir(parents=True, exist_ok=True)
    with LOG.open("a", encoding="utf-8") as fh:
        fh.write(f"[{datetime.now(UTC).isoformat(timespec='seconds')}] {mensaje}\n")
    try:
        print(mensaje)
    except UnicodeEncodeError:
        print(mensaje.encode("ascii", "replace").decode("ascii"))


def conectar(args: argparse.Namespace):
    import psycopg2

    if args.dsn:
        return psycopg2.connect(args.dsn, connect_timeout=20)
    faltan = [v for v in ("DB_NAME", "DB_USER", "DB_PASSWORD") if not os.environ.get(v)]
    if faltan:
        registrar(f"ERROR: faltan variables de entorno: {', '.join(faltan)} (o usa --dsn)")
        sys.exit(2)
    return psycopg2.connect(
        host=os.environ.get("DB_HOST", "localhost"),
        port=int(os.environ.get("DB_PORT", "5432")),
        dbname=os.environ["DB_NAME"],
        user=os.environ["DB_USER"],
        password=os.environ["DB_PASSWORD"],
        sslmode=os.environ.get("DB_SSLMODE", "prefer"),
        connect_timeout=20,
    )


def estado_actual(conn) -> dict:
    with conn.cursor() as cur:
        cur.execute(VERIFICACION)
        cols = [d[0] for d in cur.description]
        estado = dict(zip(cols, cur.fetchone(), strict=True))
    # `filas_metrica` va aparte: la tabla puede no existir todavía.
    if estado["tabla_ok"]:
        with conn.cursor() as cur:
            cur.execute(FILAS_METRICA)
            estado["filas_metrica"] = cur.fetchone()[0]
    else:
        estado["filas_metrica"] = 0
    return estado


def main() -> int:
    p = argparse.ArgumentParser(
        description="Migración D-163: tabla despacho_metrica_diaria + triggers del despacho."
    )
    p.add_argument(
        "--aplicar", action="store_true", help="Escribe los cambios (por defecto simula)"
    )
    p.add_argument("--si", action="store_true", help="Omite la confirmación interactiva")
    p.add_argument("--dsn", default=None, help="Cadena de conexión (alternativa a DB_*)")
    args = p.parse_args()

    conn = conectar(args)
    try:
        conn.autocommit = False
        estado = estado_actual(conn)
        registrar("=" * 78)
        registrar("MIGRACIÓN D-163 (métricas diarias persistidas del despacho)")
        registrar(f"modo={'APLICAR' if args.aplicar else 'SIMULACIÓN'}")
        registrar(f"estado actual: {estado}")

        if estado["triggers_ok"] >= 2 and estado["funcion_ok"] and estado["politica_ok"]:
            registrar("✓ La base YA está migrada: no hay cambios pendientes.")
            return 0
        registrar(f"pasos pendientes: {len(PASOS)}")
        if not args.aplicar:
            registrar("(simulación) Ejecuta con --aplicar --si para escribir.")
            return 0

        with conn.cursor() as cur:
            for paso in PASOS:
                cur.execute(paso)
            cur.execute(RECALCULO)
        conn.commit()

        post = estado_actual(conn)
        ok = (
            post["tabla_ok"] == 1
            and post["funcion_ok"] >= 1
            and post["triggers_ok"] >= 2
            and post["politica_ok"] >= 1
        )
        if ok:
            registrar(f"verificación post-migración: {post}")
            rec = "recalculadas" if post["filas_metrica"] > 0 else "sin filas (sin despachos)"
            registrar(f"✓ MIGRACIÓN COMPLETA Y VERIFICADA ({rec})")
            return 0
        registrar(f"ERROR: el estado post-migración no está completo: {post}")
        return 4
    finally:
        conn.close()


if __name__ == "__main__":
    sys.exit(main())
